"""Side-by-side visual examples (source image | tactile SVG) for one benchmark run.

    python -m evaluation.examples model_a_v2-all --split test

Writes ``evaluation/reports/examples/<run>/<image_id>.jpg``. Only synthetic
images are rendered; they are generated by this repository.
"""

from __future__ import annotations

import argparse
import json

import cv2

from evaluation.run_real import ROOT, render_svg, side_by_side

DATASET = ROOT / "evaluation" / "dataset"
RESULTS = ROOT / "evaluation" / "results"


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser()
    p.add_argument("run")
    p.add_argument("--split", default="test")
    args = p.parse_args(argv)
    ids = (DATASET / "splits" / f"{args.split}.txt").read_text().split()
    out = ROOT / "evaluation" / "reports" / "examples" / args.run
    out.mkdir(parents=True, exist_ok=True)
    for image_id in ids:
        path = RESULTS / args.run / "per_image" / f"{image_id}.json"
        if not path.exists():
            continue
        row = json.loads(path.read_text())
        gt = json.loads((DATASET / "annotations" / f"{image_id}.json").read_text())
        bgr = cv2.imread(str(DATASET / gt["file"]))
        svg = row["captured"].get("tactile_svg")
        s = row["score"]
        if s.get("failed"):
            title = f"{image_id} {row['difficulty']}: FAILED ({s.get('error', '')[:40]})"
        else:
            o = s["objects_final"]
            title = (f"{image_id} {row['difficulty']}: essential {o['essential_found_structural']}/{o['gt_essential']}, "
                     f"labels {s['labels']['detected']}/{s['labels']['gt_essential']}, "
                     f"QA {'pass' if s['qa']['passes'] else 'BLOCKED'}")
        cv2.imwrite(str(out / f"{image_id}.jpg"), side_by_side(bgr, render_svg(svg) if svg else None, title),
                    [cv2.IMWRITE_JPEG_QUALITY, 80])
    print(out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
